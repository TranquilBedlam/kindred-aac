const {test,expect}=require('@playwright/test');
const {spawn}=require('node:child_process');
let server;
test.beforeAll(async()=>{
 server=spawn('python3',['-m','http.server','8765','--bind','127.0.0.1'],{stdio:'ignore'});
 await new Promise(resolve=>setTimeout(resolve,1200));
});
test.afterAll(()=>server?.kill());
test('parent unlock, reordering, persistence, AAC speech interaction and lock',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/');
 await page.getByRole('button',{name:/Parent Settings/}).click();
 const q=await page.locator('#parent-question').innerText();
 const match=q.match(/(\d+)\s*\+\s*(\d+)/);
 expect(match).not.toBeNull();
 await page.locator('#parent-answer').fill(String(Number(match[1])+Number(match[2])));
 await page.getByRole('button',{name:'Unlock parent settings'}).click();
 await expect(page.locator('#caregiver-editor')).toBeVisible();
 const rows=page.locator('#custom-list .custom-row');
 await expect(rows.first()).toContainText('Help');
 const before=await rows.evaluateAll(nodes=>nodes.map(n=>n.dataset.wordId));
 await page.locator('#custom-list .custom-row').filter({hasText:'Water'}).locator('button[aria-label^="Move Water up"]').click();
 const after=await rows.evaluateAll(nodes=>nodes.map(n=>n.dataset.wordId));
 expect(after.indexOf('water')).toBe(before.indexOf('water')-1);
 await page.reload();
 await page.getByRole('button',{name:/Parent Settings/}).click();
 const q2=await page.locator('#parent-question').innerText();
 const match2=q2.match(/(\d+)\s*\+\s*(\d+)/);
 await page.locator('#parent-answer').fill(String(Number(match2[1])+Number(match2[2])));
 await page.getByRole('button',{name:'Unlock parent settings'}).click();
 expect(await rows.evaluateAll(nodes=>nodes.map(n=>n.dataset.wordId))).toEqual(after);
 const water=page.locator('#custom-list .custom-row[data-word-id="water"]');
 const help=page.locator('#custom-list .custom-row[data-word-id="help"]');
 await water.locator('.drag-handle').dragTo(help.locator('.drag-handle'),{targetPosition:{x:10,y:12}});
 await expect(rows.first()).toHaveAttribute('data-word-id','water');
 await page.locator('#exit-parent').click();
 await page.locator('#talk').click();
 const padNames=await page.locator('#vocab button').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('aria-label')));
 expect(padNames[0]).toBe('Water');
 await page.locator('#vocab button').first().click();
 await expect(page.locator('#phrase')).toContainText('Water');
 expect(errors).toEqual([]);
});
